import { test, after } from "node:test";
import assert from "node:assert/strict";
import ExcelJS from "exceljs";
import { sql } from "drizzle-orm";
import { getDb, closeDb } from "../db/client";
import { exportWar, worksheetName } from "../modules/games/export";
import { saveDraft, publishGame, getDraft } from "../modules/games/admin";
import { endGame, joinGame } from "../modules/games/lifecycle";
import { submitRanking } from "../modules/allocation/service";
import { draftFixture } from "./fixtures";
import { GET } from "../app/api/admin/games/[gameId]/export/route";
