after(closeDb);
test("worksheet names are safe, unique ignoring case, limited to 31 characters and handle reserved/empty names", () => {
  const used = new Set<string>();
  for (const [index, raw] of ["[]?:/*\\", "a".repeat(80), "A".repeat(80), "'apostrophe'", "History", "=formula", " 'quoted' ", "a".repeat(30) + "'suffix"].entries()) {
    const name = worksheetName(raw, used, index);
    assert.ok(name.length > 0 && name.length <= 31);
    assert.ok(!/[\\/?*:[\]]/.test(name));
    assert.ok(!name.startsWith("'") && !name.endsWith("'"));
  }
  assert.equal(used.size, 8);
});
test("admin XLSX uses exact columns, all packages, FCFS ordering, text cells and authoritative receipt dates", async () => {
  const f = await draftFixture(3);
  const now = new Date((await getDb().execute(sql`SELECT clock_timestamp() AS now`)).rows[0].now as string);
  const names = ["Un / deux: trois?".repeat(3), "Un \\ deux: trois?".repeat(3), "=HYPERLINK(\"x\")"];
  const saved = await saveDraft(f.admin, { ...f.input, startsAt: new Date(now.getTime() - 60000).toISOString(), packages: names.map(name => ({ name, capacity: 3 })) });
  await publishGame(f.admin, saved.id);
  const game = await getDraft(f.admin, saved.id);
  const formulaEmail = `=cmd+${f.students[1].id}@example.invalid`;
  const textNim = `00${f.students[1].id.replaceAll("-", "").toUpperCase()}`;
  await getDb().execute(sql`UPDATE users SET full_name='=HYPERLINK("evil")',email_normalized=${formulaEmail},nim=${textNim} WHERE id=${f.students[1].id}`);
  await getDb().execute(sql`UPDATE users SET nim=NULL WHERE id=${f.students[0].id}`);
  for (const student of f.students) await joinGame(student, saved.id, { accepted: true, acceptedTermsVersion: game.termsVersion });
  const first = await submitRanking(f.students[1], saved.id, game.packages.map(p => p.id));
  const second = await submitRanking(f.students[0], saved.id, game.packages.map(p => p.id));
  await assert.rejects(exportWar(f.students[0], saved.id), { code: "FORBIDDEN" });
  const report = await exportWar(f.admin, saved.id);
  assert.equal(report.final, false);
  assert.match(report.filename, /^[a-zA-Z0-9_-]+\.xlsx$/);
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(report.buffer);
  assert.equal(workbook.worksheets.length, 3);
  assert.match(workbook.subject, /sementara/);
  const sheet = workbook.worksheets[0];
  assert.deepEqual((sheet.getRow(1).values as unknown[]).slice(1), [ "No", "Nama Lengkap", "NIM", "Email", "Waktu Diterima"]);
  assert.equal(sheet.getCell("B2").value, '=HYPERLINK("evil")');
  assert.equal(sheet.getCell("B2").type, ExcelJS.ValueType.String);
  assert.equal(sheet.getCell("D2").value, formulaEmail);
  assert.equal(sheet.getCell("D2").type, ExcelJS.ValueType.String);
  assert.equal(sheet.getCell("C2").value, textNim);
  assert.equal(sheet.getCell("C3").value, "—");
  assert.equal(sheet.getCell("E2").value, jakartaPrecise(first.acceptedAt, true));
  assert.equal(sheet.getCell("E3").value, jakartaPrecise(second.acceptedAt, true));
  assert.equal(sheet.getCell("A2").value, 1);
  assert.equal(sheet.getCell("A3").value, 2);
  assert.equal(sheet.views[0].state, "frozen");
  assert.equal(workbook.worksheets[1].rowCount, 1);
  assert.equal(workbook.worksheets[2].rowCount, 1);
  assert.equal(new Set(workbook.worksheets.map(s => s.name.toLowerCase())).size, 3);
  await endGame(f.admin, saved.id, "Selesai pengujian ekspor");
  const final = await exportWar(f.admin, saved.id);
  assert.ok(final.final);
  await assert.rejects(exportWar(f.admin, crypto.randomUUID()), { code: "NOT_FOUND" });
});
